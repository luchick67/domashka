import csv
a = [
    ["Товар", "Цена за штуку", "Количество"],
    ["Тетрадь", "2.50", "4"],
    ["Ручка", "1.20", "3"],
    ["Папка", "4.00", "2"],
    ["Маркер", "3.30", "1"]]
with open("purchases.csv", "w", encoding="utf-8", newline="") as f:   # Создаём CSV-файл и записываем таблицу
    w = csv.writer(f)
    w.writerows(a)
s = 0         # Переменная для общей суммы покупок
with open("purchases.csv", "r", encoding="utf-8") as f:     # Читаем данные из CSV-файла
    r = csv.reader(f)
    next(r)                   # Пропускаем строку с заголовками
    for x in r:        # Перебираем строки с товарами
        n, p, k = x          # Разделяем строку на название, цену и кол-во
        c = float(p) * int(k)          # Считаем стоимость одного товара
        s += c                          # Прибавляем к общей сумме
        print(f"{n}: цена {p}, кол-во {k} — стоимость {c:.2f}")
print(f"\nОбщая сумма покупок: {s:.2f}")  # Выводим общую стоимость